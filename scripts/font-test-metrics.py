"""Rebuild test glyph advances after an intentional Fontsource update.
Developer-only: Python + fontTools[woff]. The program and CI do not need Python.
"""
from pathlib import Path
import hashlib
import json
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
alphabet = ''.join(chr(c) for c in [*range(32, 127), *range(0x400, 0x460), 0xab, 0xbb, 0xb7, 0x2013, 0x2014, 0x2026, 0x2116])
metrics = {}
hashes = {}
for family, prefix in [('pt-sans', 'sans'), ('pt-sans-narrow', 'narrow')]:
    for weight in [400, 700]:
        widths = {}
        for subset in ['latin', 'cyrillic']:
            relative = f'@fontsource/{family}/files/{family}-{subset}-{weight}-normal.woff2'
            path = root / 'node_modules' / relative
            hashes[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
            font = TTFont(path)
            for code, glyph in font.getBestCmap().items():
                widths[chr(code)] = font['hmtx'][glyph][0] / font['head'].unitsPerEm
        metrics[f'{prefix}{weight}'] = [widths.get(char, 0.6) for char in alphabet]
output = root / 'libs/documents/application/src/lib/testing/font-advances.ts'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('// Generated by scripts/font-test-metrics.py; Fontsource 5.3.0, OFL-1.1.\n'
    + 'export const glyphs = ' + json.dumps(alphabet, ensure_ascii=False) + '\n'
    + 'export const advances = ' + json.dumps(metrics, ensure_ascii=False) + '\n'
    + 'export const fontHashes = ' + json.dumps(hashes, ensure_ascii=False) + '\n')
